#include <iostream>

int main()
{
	std::cout << "T1 " << 5 << "\n";                             //字面值，不可修改
	int x{ 5 };                                                  //变量，可修改
	                                                             //字面值直接编进可执行文件；变量是内存里的位置
	std::cout << "T2 " << x << "\n";
	std::cout << "T3 " << -5 << "\n";                            //一元操作符
	std::cout << "T4 " << 5 - 3 << "\n";                         //二元操作符
	std::cout << "T5 " << 2 * 3 + 4 << "\n";
	std::cout << "T6 " << 2 + 3 * 4 << "\n";                     //四则混合运算法则，括号 → 指数 → 乘除 → 加减（PEMDAS），同级从左到右
	std::cout << "T7 " << (2 + 3) * 4 << "\n";
	std::cout << "T8 " << 10 - 4 / 2 << "\n";
	std::cout << "T9 " << 10 / 4 << "\n";                        // 观察：得到 2 而不是 2.5（整数字面值相除→整数除法，小数被丢弃）
	std::cout << "T10 " << "A" << "B" << "C" << "\n";            //操作符的输出用作另一操作符的输入，因为 << 返回左操作数 std::cout
	int a{};
	int b{};
	a = b = 5;                                                   //等价于  a = (b = 5)
	std::cout << "T11 " << a << " " << b << "\n";
	                                                             // 副作用：操作符除了产生返回值，还有可观察的效果
	                                                             // 本程序里：<< 的副作用是"打印到控制台"；= 的副作用是"改变变量里存的值"
	return 0;
}